-- ============================================================================
-- RentLoop Database Schema (Supabase PostgreSQL)
-- Tables: profiles, listings, listing_images, bookings
-- View:   public_profiles (safe public view exposing only full_name & institution)
-- ============================================================================

-- Required to combine listing_id (=) and daterange (&&) in the EXCLUDE constraint
CREATE EXTENSION IF NOT EXISTS btree_gist;


-- ============================================================================
-- 1. TABLE: profiles & PUBLIC VIEW: public_profiles
-- ============================================================================

CREATE TABLE public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  full_name TEXT NOT NULL CHECK (char_length(btrim(full_name)) > 0),
  email TEXT NOT NULL UNIQUE CHECK (position('@' IN email) > 1),
  phone TEXT,
  institution TEXT NOT NULL CHECK (char_length(btrim(institution)) > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Safe view for other authenticated students: exposes only name and institution
-- (never exposes email or phone).
CREATE OR REPLACE VIEW public.public_profiles AS
SELECT id, full_name, institution
FROM public.profiles;

REVOKE ALL ON public.public_profiles FROM PUBLIC, anon;
GRANT SELECT ON public.public_profiles TO authenticated;

-- Automatically creates a profile when a new user signs up in Supabase Auth
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.profiles (id, full_name, email, phone, institution)
  VALUES (
    NEW.id,
    COALESCE(NULLIF(btrim(NEW.raw_user_meta_data ->> 'full_name'), ''), 'Student'),
    NEW.email,
    NULLIF(btrim(NEW.raw_user_meta_data ->> 'phone'), ''),
    COALESCE(NULLIF(btrim(NEW.raw_user_meta_data ->> 'institution'), ''), 'Campus')
  )
  ON CONFLICT (id) DO NOTHING;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW
  EXECUTE FUNCTION public.handle_new_user();

-- One-time backfill for any accounts registered before this schema was run
INSERT INTO public.profiles (id, full_name, email, phone, institution)
SELECT
  u.id,
  COALESCE(NULLIF(btrim(u.raw_user_meta_data ->> 'full_name'), ''), 'Student'),
  u.email,
  NULLIF(btrim(u.raw_user_meta_data ->> 'phone'), ''),
  COALESCE(NULLIF(btrim(u.raw_user_meta_data ->> 'institution'), ''), 'Campus')
FROM auth.users u
WHERE u.email IS NOT NULL
ON CONFLICT (id) DO NOTHING;


-- ============================================================================
-- 2. TABLE: listings
-- ============================================================================

CREATE TABLE public.listings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  item_name TEXT NOT NULL CHECK (char_length(btrim(item_name)) > 0),
  category TEXT NOT NULL CHECK (
    category IN (
      'Photography & Video',
      'Electronics & Audio',
      'Sports & Mobility',
      'Academic & STEM Tools',
      'Event Equipment',
      'Other Campus Gear'
    )
  ),
  brand_model TEXT,
  description TEXT NOT NULL CHECK (char_length(btrim(description)) > 0 AND char_length(description) <= 800),
  condition TEXT NOT NULL CHECK (condition IN ('Like New', 'Excellent', 'Good', 'Fair')),
  daily_price INTEGER NOT NULL CHECK (daily_price > 0),
  pickup_location TEXT NOT NULL CHECK (char_length(btrim(pickup_location)) > 0),
  availability_status TEXT NOT NULL DEFAULT 'available' CHECK (availability_status IN ('available', 'paused')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- ============================================================================
-- 3. TABLE: listing_images
-- ============================================================================

CREATE TABLE public.listing_images (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  listing_id BIGINT NOT NULL REFERENCES public.listings(id) ON DELETE CASCADE,
  image_url TEXT NOT NULL CHECK (char_length(btrim(image_url)) > 0),
  display_order SMALLINT NOT NULL DEFAULT 0 CHECK (display_order >= 0 AND display_order < 5),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT listing_images_unique_order UNIQUE (listing_id, display_order)
);


-- ============================================================================
-- 4. TABLE: bookings & BUSINESS RULE TRIGGER
-- ============================================================================

CREATE TABLE public.bookings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  listing_id BIGINT NOT NULL REFERENCES public.listings(id) ON DELETE CASCADE,
  renter_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  daily_price INTEGER NOT NULL CHECK (daily_price > 0),
  total_price INTEGER NOT NULL,
  booking_status TEXT NOT NULL DEFAULT 'pending' CHECK (
    booking_status IN ('pending', 'approved', 'declined', 'returned')
  ),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  CONSTRAINT bookings_valid_dates CHECK (end_date >= start_date),

  -- Inclusive days = (end_date - start_date) + 1; total_price = days * daily_price
  CONSTRAINT bookings_total_price_check CHECK (
    total_price > 0
    AND total_price = ((end_date - start_date) + 1) * daily_price
  ),

  -- Blocks overlapping 'approved' bookings (concurrency-safe); 'pending' requests may overlap
  CONSTRAINT bookings_no_overlapping_approved
    EXCLUDE USING gist (
      listing_id WITH =,
      daterange(start_date, end_date, '[]') WITH &&
    )
    WHERE (booking_status = 'approved')
);

-- Prevents self-renting, checks listing availability/price, and locks core booking fields
CREATE OR REPLACE FUNCTION public.check_booking_rules()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_owner_id UUID;
  v_daily_price INTEGER;
  v_status TEXT;
BEGIN
  SELECT owner_id, daily_price, availability_status
  INTO v_owner_id, v_daily_price, v_status
  FROM public.listings
  WHERE id = NEW.listing_id;

  IF v_owner_id = NEW.renter_id THEN
    RAISE EXCEPTION 'Students cannot rent their own listing.';
  END IF;

  IF TG_OP = 'INSERT' THEN
    IF v_status <> 'available' THEN
      RAISE EXCEPTION 'This listing is currently paused.';
    END IF;
    IF NEW.start_date < CURRENT_DATE THEN
      RAISE EXCEPTION 'Start date cannot be in the past.';
    END IF;
    IF NEW.daily_price <> v_daily_price THEN
      RAISE EXCEPTION 'Booking daily price must match the listing daily price.';
    END IF;
  ELSIF TG_OP = 'UPDATE' THEN
    IF NEW.listing_id <> OLD.listing_id OR NEW.renter_id <> OLD.renter_id
       OR NEW.start_date <> OLD.start_date OR NEW.end_date <> OLD.end_date
       OR NEW.daily_price <> OLD.daily_price OR NEW.total_price <> OLD.total_price THEN
      RAISE EXCEPTION 'Booking dates, price, and participants cannot be changed.';
    END IF;
    IF NEW.booking_status = 'approved' AND v_status <> 'available' THEN
      RAISE EXCEPTION 'Cannot approve a booking while the listing is paused.';
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_check_booking_rules ON public.bookings;
CREATE TRIGGER trg_check_booking_rules
  BEFORE INSERT OR UPDATE ON public.bookings
  FOR EACH ROW
  EXECUTE FUNCTION public.check_booking_rules();


-- ============================================================================
-- 5. ROW LEVEL SECURITY (RLS) POLICIES
-- ============================================================================

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.listings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.listing_images ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bookings ENABLE ROW LEVEL SECURITY;

-- profiles: strictly private to the account owner (peers use public_profiles view)
CREATE POLICY "profiles_select_own" ON public.profiles
  FOR SELECT TO authenticated USING (auth.uid() = id);

CREATE POLICY "profiles_insert_own" ON public.profiles
  FOR INSERT TO authenticated WITH CHECK (auth.uid() = id);

CREATE POLICY "profiles_update_own" ON public.profiles
  FOR UPDATE TO authenticated USING (auth.uid() = id) WITH CHECK (auth.uid() = id);

-- listings: public can view 'available' items; owners can manage all of their own items
CREATE POLICY "listings_select_visible" ON public.listings
  FOR SELECT USING (availability_status = 'available' OR auth.uid() = owner_id);

CREATE POLICY "listings_manage_own" ON public.listings
  FOR ALL TO authenticated
  USING (auth.uid() = owner_id)
  WITH CHECK (auth.uid() = owner_id);

-- listing_images: readable when parent listing is visible; writable only by listing owner
CREATE POLICY "listing_images_select_visible" ON public.listing_images
  FOR SELECT USING (
    EXISTS (
      SELECT 1 FROM public.listings l
      WHERE l.id = listing_images.listing_id
        AND (l.availability_status = 'available' OR l.owner_id = auth.uid())
    )
  );

CREATE POLICY "listing_images_manage_own" ON public.listing_images
  FOR ALL TO authenticated
  USING (EXISTS (SELECT 1 FROM public.listings l WHERE l.id = listing_images.listing_id AND l.owner_id = auth.uid()))
  WITH CHECK (EXISTS (SELECT 1 FROM public.listings l WHERE l.id = listing_images.listing_id AND l.owner_id = auth.uid()));

-- bookings: visible only to renter and listing owner; renter inserts pending; owner updates status
CREATE POLICY "bookings_select_participants" ON public.bookings
  FOR SELECT TO authenticated USING (
    auth.uid() = renter_id
    OR EXISTS (SELECT 1 FROM public.listings l WHERE l.id = bookings.listing_id AND l.owner_id = auth.uid())
  );

CREATE POLICY "bookings_insert_renter" ON public.bookings
  FOR INSERT TO authenticated WITH CHECK (auth.uid() = renter_id AND booking_status = 'pending');

CREATE POLICY "bookings_update_owner" ON public.bookings
  FOR UPDATE TO authenticated
  USING (EXISTS (SELECT 1 FROM public.listings l WHERE l.id = bookings.listing_id AND l.owner_id = auth.uid()))
  WITH CHECK (EXISTS (SELECT 1 FROM public.listings l WHERE l.id = bookings.listing_id AND l.owner_id = auth.uid()));


-- ============================================================================
-- 6. TABLE PERMISSIONS (GRANTS)
-- RLS policies filter which rows a user can access; these GRANT statements
-- provide the minimum table- and column-level privileges required.
-- (public_profiles SELECT for authenticated is already granted in Section 1.)
-- ============================================================================

-- Unauthenticated visitors can browse public listings and their photos
GRANT SELECT ON public.listings, public.listing_images TO anon;

-- Authenticated students can view and update their own profile
GRANT SELECT, INSERT, UPDATE ON public.profiles TO authenticated;

-- Authenticated students can view, create, edit/pause, and delete their own listings & photos
GRANT SELECT, INSERT, UPDATE, DELETE ON public.listings, public.listing_images TO authenticated;

-- Authenticated students can view bookings and submit requests;
-- only booking_status can be updated (restricted to the listing owner by RLS)
GRANT SELECT, INSERT ON public.bookings TO authenticated;
GRANT UPDATE (booking_status) ON public.bookings TO authenticated;

